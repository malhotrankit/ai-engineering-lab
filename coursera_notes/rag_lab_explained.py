"""
LAB SECTION: "WRAP UP AND MAKE IT AN AGENT" vs REALITY
------------------------------------------------------
In the lab notebook cell 88, the author provides an interactive `while True:` loop titled:
"### Wrap up and make it an agent"

CRITICAL INTERVIEW DISTINCTION:
1. Is a `while True:` CLI loop an AI Agent? 
   NO. A `while True:` loop accepting terminal user input is simply an **Interactive CLI Chatbot Wrapper**.
   
2. What makes a system a REAL "AI Agent"?
   A real Agent operates on an **Agentic Loop** (ReAct: Thought ➔ Action ➔ Observation).
   It has access to external tools (calculators, web search, database query functions) and autonomously
   decides WHICH tool to call based on user input, rather than just running a fixed RAG chain.

LAB EXERCISES COVERED:
----------------------
- Exercise 1 (Multi-Document Loading):
    url = 'https://cf-courses-data.s3.us.cloud-object-storage.appdomain.cloud/XVnuuEg94sAE4S_xAsGxBA.txt'
    wget.download(url, out='stateOfUnion.txt')
- Exercise 2 (Source Citations):
    Setting `return_source_documents=True` on the chain and reading `result['source_documents'][0]`.
- Exercise 3 (Multi-Model Routing):
    Swapping IBM WatsonX model_id from Llama 3 to Mistral:
    `model_id = 'mistralai/mistral-small-3-1-24b-instruct-2503'`
"""

def interactive_rag_bot():
    """
    Interactive CLI loop demonstrating the lab's conversational RAG chatbot interface.
    Type 'quit', 'exit', or 'bye' to terminate the loop.
    """
    print("\n--- INTERACTIVE RAG CHATBOT LOOP STARTED ---")
    print("Type 'quit', 'exit', or 'bye' to stop the chatbot.\n")
    
    # 1. INITIALIZE CONVERSATIONAL MEMORY
    #  - `memory_key="chat_history"`: Specifies the exact key name under which past messages are stored.
    #  - `return_messages=True`: Crucial! Returns structured message objects ([HumanMessage, AIMessage]) 
    #    rather than a flat, raw text string.
    bot_memory = ConversationBufferMemory(
        memory_key="chat_history", 
        return_messages=True
    )
    
    # 2. CONSTRUCT CONVERSATIONAL RETRIEVAL CHAIN
    #  - `llm=llama_3_llm`: Specifies the foundation model (e.g. Llama 3) to generate final answers.
    #  - `chain_type="stuff"`: Concatenates (stuffs) all retrieved vector chunks into one single prompt context.
    #  - `retriever=docsearch.as_retriever()`: Converts Chroma vector DB into a retriever to fetch top matching chunks.
    #  - `memory=bot_memory`: Binds memory so the chain automatically tracks & injects prior context into each question.
    #  - `return_source_documents=True`: (Notebook Exercise 2) Instructs the chain to return the exact source 
    #    document objects used to build the answer for ground-truth citation auditing.
    bot_qa = ConversationalRetrievalChain.from_llm(
        llm=llama_3_llm,
        chain_type="stuff",
        retriever=docsearch.as_retriever(),
        memory=bot_memory,
        return_source_documents=True
    )
    
    while True:
        try:
            user_input = input("User Question: ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\nAnswer: Goodbye!")
            break

        if not user_input:
            continue

        if user_input.lower() in ["quit", "exit", "bye"]:
            print("Answer: Goodbye!")
            break
            
        # Execute query through conversational RAG chain
        # NOTE ON NOTEBOOK CELL 90 PATTERN:
        # In cell 90 of the lab notebook, the author manually wrote:
        #   result = qa({"question": query}, {"chat_history": history})
        #   history.append((query, result["answer"]))
        #
        # INSIGHT: Because `bot_memory` (ConversationBufferMemory) is passed to `bot_qa`, 
        # LangChain AUTOMATICALLY saves the user query and AI answer into memory during `.invoke()`.
        # Manually maintaining `history = []` and appending tuples is redundant boilerplate from older LangChain versions.
        bot_response = bot_qa.invoke({"question": user_input})
        
        print(f"AI Answer: {bot_response['answer']}")
        
        # Exercise 2: Print top source document citation if available
        if bot_response.get("source_documents"):
            top_doc = bot_response["source_documents"][0]
            print(f"  📌 Citation Source: {top_doc.metadata.get('source', 'Unknown')} | Snippet: {top_doc.page_content[:100]}...\n")

