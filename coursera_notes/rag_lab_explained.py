print("\nRETRIEVED SOURCE CITATION (First Source Document):")
first_source = result_4a["source_documents"][0]
print(f"Source Content Snippet:\n{first_source.page_content[:200]}...")
print(f"Source Metadata: {first_source.metadata}")


# -----------------------------------------------------------------------------
# STEP 5: CONVERSATIONAL MEMORY (LEGACY vs. MODERN MEMORY HANDLING)
# -----------------------------------------------------------------------------

"""
LEGACY MEMORY HANDLING vs MODERN MEMORY HANDLING
------------------------------------------------
1. Legacy Callback (`get_chat_history=lambda h: h`):
   In older LangChain code, `ConversationalRetrievalChain` attempted to reformat chat history
   into a single plain-text string by default. Developers had to supply a custom identity callback:
   
       get_chat_history=lambda h: h
   
   This forced LangChain to take raw memory objects 'h' and pass them through without reformatting.

2. Lab Redundancy:
   `ConversationBufferMemory` AUTOMATICALLY intercepts and appends user questions and AI answers
   to memory behind the scenes. In the original lab, the author manually created a separate `history = []`
   list and called `history.append()`, which was completely redundant!

3. Modern Memory Standard:
   Instead of using custom `get_chat_history` callbacks, modern prompt templates use:
   
       MessagesPlaceholder(variable_name="chat_history")
   
   When `ConversationBufferMemory(memory_key="chat_history", return_messages=True)` is used, it outputs
   a list of message objects `[HumanMessage, AIMessage]`. `MessagesPlaceholder` dynamically injects
   that history directly into the prompt template at runtime!
"""

print("\n--- DEMONSTRATING CONVERSATIONAL MEMORY (AUTOMATIC RECOLLECTION) ---")

# Modern Memory Setup: return_messages=True outputs structured Message objects for chat_history
memory = ConversationBufferMemory(memory_key="chat_history", return_messages=True)

conv_qa = ConversationalRetrievalChain.from_llm(
    llm=llama_3_llm, 
    chain_type="stuff", 
    retriever=docsearch.as_retriever(), 
    memory=memory, 
    return_source_documents=False
)

# Turn 1: Establish context
q1 = "What is mobile policy?"
res1 = conv_qa.invoke({"question": q1})
print(f"\nUser: {q1}")
print(f"AI: {res1['answer']}")

# Turn 2: Ask follow-up with ambiguous pronoun ("it")
# ConversationBufferMemory automatically passed Turn 1 into history, so the LLM knows "it" refers to "mobile policy"!
q2 = "What is the main aim of it?"
res2 = conv_qa.invoke({"question": q2})
print(f"\nUser: {q2}")
print(f"AI: {res2['answer']}")


