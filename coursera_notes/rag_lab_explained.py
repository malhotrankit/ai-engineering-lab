import os
import warnings

# Suppress harmless warnings generated by old LangChain/Transformer libraries
warnings.filterwarnings('ignore')

# -----------------------------------------------------------------------------
# STEP 1: IMPORTING THE REQUIRED LIBRARIES
# -----------------------------------------------------------------------------

# Document Loaders convert raw external files (.txt, .pdf, .html) into LangChain `Document` objects.
from langchain.document_loaders import TextLoader

# Text Splitters chop long document strings into smaller, manageable chunks.
from langchain.text_splitter import CharacterTextSplitter, RecursiveCharacterTextSplitter

# VectorStore (Chroma) acts as our vector database graph to store and search embeddings.
from langchain.vectorstores import Chroma

# Embedding Model transforms raw string chunks into numerical vector arrays.
from langchain.embeddings import HuggingFaceEmbeddings

# Legacy Chains (RetrievalQA & ConversationalRetrievalChain)
from langchain.chains import RetrievalQA, ConversationalRetrievalChain
from langchain.prompts import PromptTemplate
from langchain.memory import ConversationBufferMemory

# Modern LCEL Alternatives (for comparison)
from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.messages import HumanMessage, AIMessage

# IBM WatsonX SDK Imports (Used in IBM Coursera environment)
from ibm_watsonx_ai.foundation_models import Model
from ibm_watsonx_ai.metanames import GenTextParamsMetaNames as GenParams
from ibm_watsonx_ai.foundation_models.utils.enums import ModelTypes, DecodingMethods
from ibm_watson_machine_learning.foundation_models.extensions.langchain import WatsonxLLM

import wget


# -----------------------------------------------------------------------------
# STEP 2: DOCUMENT INDEXING (LOAD ➔ SPLIT ➔ EMBED & STORE)
# -----------------------------------------------------------------------------

# 1. DOWNLOAD THE PRIVATE DOCUMENT
# In this lab, a text file containing company policies is downloaded.
filename = 'companyPolicies.txt'
url = 'https://cf-courses-data.s3.us.cloud-object-storage.appdomain.cloud/6JDbUb_L3egv_eOkouY71A.txt'

if not os.path.exists(filename):
    print("Downloading document...")
    wget.download(url, out=filename)
    print("\nFile downloaded successfully.")

# 2. LOAD THE DOCUMENT
# `TextLoader` reads the text file and wraps it inside a LangChain `Document` object:
# Document(page_content="...", metadata={'source': 'companyPolicies.txt'})
loader = TextLoader(filename)
documents = loader.load()

# 3. SPLIT THE DOCUMENT INTO CHUNKS
# Why split? 
#  - LLMs have finite context windows.
#  - Small, targeted text chunks produce much sharper vector similarity scores than a 50-page wall of text.
# 
# Lab Code uses CharacterTextSplitter:
#  - `chunk_size=1000`: Maximum characters per chunk.
#  - `chunk_overlap=0`: No overlapping characters between chunks.
text_splitter = CharacterTextSplitter(chunk_size=1000, chunk_overlap=0)
texts = text_splitter.split_documents(documents)
print(f"Total chunks created: {len(texts)}")

"""
PRO TIP / INTERVIEW NOTE ON SPLITTERS:
--------------------------------------
`CharacterTextSplitter` blindly cuts text every 1000 characters, which can chop sentences in half.
In modern production, we use `RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=100)`.
`Recursive` tries to split on paragraphs ('\n\n') first, then sentences ('. '), then words (' '),
preserving semantic sentence boundaries!
"""

# 4. EMBED AND STORE IN VECTOR DATABASE (CHROMA)
# HuggingFaceEmbeddings uses a local open-source model (e.g. all-MiniLM-L6-v2) to map text to vectors.
embeddings = HuggingFaceEmbeddings()

# `Chroma.from_documents(...)` performs 3 operations at once:
#   a. Takes the list of text chunks (`texts`).
#   b. Converts each chunk into a vector via `embeddings`.
#   c. Saves both vector + raw text + metadata into the Chroma vector database.
docsearch = Chroma.from_documents(texts, embeddings)
print("Document ingested into Chroma VectorStore successfully.")


# -----------------------------------------------------------------------------
# STEP 3: LLM MODEL CONSTRUCTION (WATSONX / LLAMA 3)
# -----------------------------------------------------------------------------

model_id = 'ibm/granite-3-8b-instruct'

# Defining Inference Parameters:
#  - `GREEDY` decoding: Always picks the #1 highest probability token. 100% deterministic & factual!
#  - `MIN_NEW_TOKENS` & `MAX_NEW_TOKENS`: Controls length bounds of response.
#  - `TEMPERATURE`: Inactive when Decoding = GREEDY, but sets creativity level if SAMPLING is used.
parameters = {
    GenParams.DECODING_METHOD: DecodingMethods.GREEDY,  
    GenParams.MIN_NEW_TOKENS: 50,
    GenParams.MAX_NEW_TOKENS: 256,
    GenParams.TEMPERATURE: 0.0
}

credentials = {
    "url": "https://us-south.ml.cloud.ibm.com"
}
project_id = "skills-network"

# Build the native IBM model object
model = Model(
    model_id=model_id,
    params=parameters,
    credentials=credentials,
    project_id=project_id
)

# Wrap IBM native model with LangChain's WatsonxLLM wrapper so it understands `.invoke()`
llama_3_llm = WatsonxLLM(model=model)


# -----------------------------------------------------------------------------
# STEP 4: BUILDING THE RAG CHAIN & GUARDRAILED PROMPTS (4 EVOLUTIONARY PATTERNS)
# -----------------------------------------------------------------------------

"""
UNDER-THE-HOOD MECHANICS: WHERE DOES {context} COME FROM?
---------------------------------------------------------
When you call a RAG chain:
  1. The input query string is passed to the retriever (`docsearch.as_retriever()`).
  2. Chroma performs similarity search and retrieves top matching chunks.
  3. All matching chunks are concatenated (stuffed) into a single context block.
  4. The stuffed text is bound to the `{context}` prompt variable.
  5. The complete prompt payload is sent to the LLM.
"""

# CUSTOM PROMPT TEMPLATE WITH ANTI-HALLUCINATION GUARDRAILS
prompt_template = """Use the information from the document to answer the question at the end. 
If you don't know the answer, just say that you don't know, definitely do not try to make up an answer.

Context:
{context}

Question: {question}
Answer:"""

PROMPT = PromptTemplate(
    template=prompt_template, 
    input_variables=["context", "question"]
)

# -----------------------------------------------------------------------------
# 4a. LEGACY LAB PATTERN (RetrievalQA.from_chain_type)
# -----------------------------------------------------------------------------
# Encapsulates retriever + prompt + LLM into 1 monolithic class instance.
chain_type_kwargs = {"prompt": PROMPT}
qa_chain = RetrievalQA.from_chain_type(
    llm=llama_3_llm, 
    chain_type="stuff",                # Stuffs all retrieved chunks into 1 single API call
    retriever=docsearch.as_retriever(), 
    chain_type_kwargs=chain_type_kwargs, 
    return_source_documents=True
)

print("\n--- [4a. LEGACY RETRIEVAL QA] EXECUTING QUERY ---")
query = "Can I eat in company vehicles?"
result_4a = qa_chain.invoke(query)
print("4a Answer:", result_4a["result"])


# -----------------------------------------------------------------------------
# 4b. PURE LCEL PIPE OPERATOR (|) SYNTAX
# -----------------------------------------------------------------------------
# Uses Python's `|` bitwise OR operator to explicitly connect Runnable components!
# 
# UNDERSTANDING THE INPUT MAPPER DICTIONARY:
# {"context": retriever | format_docs, "question": RunnablePassthrough()}
# 
# 1. RunnableParallel (Implicit): Passing a dict {...} automatically wraps keys in a
#    RunnableParallel map, executing all keys concurrently to prepare prompt inputs.
# 2. 'context': retriever | format_docs:
#    - `retriever` takes user query string -> fetches top matching Document chunks from ChromaDB.
#    - `| format_docs` pipes those Document objects to `format_docs()`, joining chunk text
#      into one string assigned to key 'context' (fills {context} in prompt).
# 3. 'question': RunnablePassthrough():
#    - Acts as a pass-through forwarding wire. Takes incoming user query string and forwards
#      it unchanged to key 'question' (fills {question} in prompt), preventing it from being lost.

from langchain_core.runnables import RunnablePassthrough
from langchain_core.output_parsers import StrOutputParser

def format_docs(docs):
    return "\n\n".join(doc.page_content for doc in docs)

retriever = docsearch.as_retriever()

pure_lcel_chain = (
    {"context": retriever | format_docs, "question": RunnablePassthrough()}
    | PROMPT
    | llama_3_llm
    | StrOutputParser()
)

print("\n--- [4b. PURE LCEL PIPE OPERATOR (|)] EXECUTING QUERY ---")
result_4b = pure_lcel_chain.invoke(query)
print("4b Answer:", result_4b)


# -----------------------------------------------------------------------------
# 4c. MODERN PRODUCTION PREFERENCE: HIGH-LEVEL FACTORY HELPERS
# -----------------------------------------------------------------------------
# Modern LangChain standard combining explicit LCEL under the hood with clean helper functions.
# Step 1: Create the document combination chain
# Step 2: Create the retrieval chain wrapping the retriever + doc chain
from langchain.chains.combine_documents import create_stuff_documents_chain
from langchain.chains import create_retrieval_chain

combine_docs_chain = create_stuff_documents_chain(llama_3_llm, PROMPT)
factory_rag_chain = create_retrieval_chain(retriever, combine_docs_chain)

print("\n--- [4c. MODERN FACTORY HELPERS] EXECUTING QUERY ---")
result_4c = factory_rag_chain.invoke({"input": query})
print("4c Answer:", result_4c["answer"])


# -----------------------------------------------------------------------------
# 4d. LLAMAINDEX QUERYENGINE PATTERN (ALTERNATIVE FRAMEWORK)
# -----------------------------------------------------------------------------
# LlamaIndex's all-in-one RAG pipeline abstraction (no pipe operator needed).
# Handles retrieval, prompt formatting, and LLM synthesis in 1 method call.
